const EPOCH = '2026-01-01T00:00:00.000Z';

const weekdayHours = (opensAt: string, closesAt: string): OperatingHours[] =>
  [0, 1, 2, 3, 4, 5, 6].map((weekday) => ({
    weekday,
    opensAt,
    closesAt,
    // Friday is free in most Palestinian municipal zones.
    closed: weekday === 5,
  }));

const allDayHours = (): OperatingHours[] =>
  [0, 1, 2, 3, 4, 5, 6].map((weekday) => ({ weekday, opensAt: '00:00', closesAt: '23:59' }));

const tariff = (
  id: string,
  name: string,
  hourlyRate: number,
  overrides: Partial<Tariff> = {},
): Tariff => ({
  id,
  name,
  hourlyRate,
  currency: 'ILS',
  incrementMinutes: 15,
  freeMinutes: 5,
  minimumCharge: 100,
  maxStayMinutes: 180,
  validFrom: EPOCH,
  ...overrides,
});

